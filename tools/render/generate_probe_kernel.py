"""Generate immutable GGX reflection kernels. No source-game inputs/dependencies."""
from pathlib import Path
import math,struct,json
def f(x):return struct.unpack("<f",struct.pack("<f",x))[0]
def kernels():
    g=f(1.324717957244746);a=f(1/g);b=f(1/f(g*g))
    result=[]
    for level,target in enumerate((16,32,64,128,128),1):
        r=f(f(level/5)**2);alpha=f(r*r);a2=f(alpha*alpha);n=target
        while True:
            taps=[]
            for i in range(n):
                x=f(.5+f(a*i))%1;y=f(.5+f(b*i))%1
                phi=f(f(2*math.pi)*x)
                c=f(math.sqrt(f(f(1-y)/f(1+f(f(a2-1)*y)))))
                sn=f(math.sqrt(max(0,f(1-f(c*c)))))
                hx=f(sn*f(math.cos(phi)));hy=f(sn*f(math.sin(phi)))
                z=f(f(2*f(c*c))-1)
                if z<1e-4:continue
                d=f(f(f(c*a2)-c)*c+1)
                pdf=f(f(a2/f(f(math.pi)*f(d*d)))*.25)
                lod=f(max(.5*math.log2(1/(n*pdf)/(4*math.pi/(6*128*128)))+1,0))
                taps.append((f(2*f(c*hx)),f(2*f(c*hy)),z,lod))
            if len(taps)>=target:break
            n+=1
        total=0.
        for t in taps:total=f(total+t[2])
        result.append(dict(level=level,roughness=r,candidates=n,taps=taps,inverseWeight=f(1/total)))
    return result
def main():
    E=Path(__file__).resolve().parents[2]
    groups=kernels();flat=[t for g in groups for t in g["taps"]]
    s="// Generated by tools/render/generate_probe_kernel.py; immutable 128-face kernels.\n"
    s+="#ifndef PROBE_KERNEL_ARRAY\n#define PROBE_KERNEL_ARRAY(name,count) const vec4 name[count]=vec4[count](\n#define PROBE_KERNEL_END );\n#endif\n"
    s+=f"PROBE_KERNEL_ARRAY(worldProbeKernel,{len(flat)})\n"
    s+=",\n".join("vec4("+",".join(format(v,".9g") if "." in format(v,".9g") or "e" in format(v,".9g") else format(v,".9g")+".0" for v in t)+")" for t in flat)+"\nPROBE_KERNEL_END\n"
    offset=0
    s+="vec3 worldProbeKernelRange(int level) {\n"
    for g in groups:
        s+=f'    if(level=={g["level"]})return vec3({offset}.0,{len(g["taps"])}.0,{g["inverseWeight"]:.9g});\n'
        offset+=len(g["taps"])
    s+="    return vec3(0.0,0.0,0.0);\n}\n"
    (E/"assets/shaders/vulkan/world_probe_kernel.glsl").write_text(s)
    print(json.dumps([{k:v for k,v in g.items() if k!="taps"} for g in groups]))
if __name__=="__main__":main()
