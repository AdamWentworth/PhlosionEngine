inline std::string hexByte(std::uint8_t value) {
    static const char* kDigits = "0123456789ABCDEF";
    std::string text = "0x";
    text.push_back(kDigits[(value >> 4u) & 0x0Fu]);
    text.push_back(kDigits[value & 0x0Fu]);
    return text;
}

// Standard base64 (RFC 4648) for the data-URI fixture. This encodes only; it is
// not a decoder under test and is never used to verify pixels.
inline std::string encodeBase64(const std::vector<std::uint8_t>& bytes) {
    static const char* kAlphabet =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::string out;
    out.reserve(((bytes.size() + 2u) / 3u) * 4u);
    std::size_t index = 0u;
    while (index + 3u <= bytes.size()) {
        const std::uint32_t block = (static_cast<std::uint32_t>(bytes[index]) << 16u) |
                                    (static_cast<std::uint32_t>(bytes[index + 1u]) << 8u) |
                                    static_cast<std::uint32_t>(bytes[index + 2u]);
        out.push_back(kAlphabet[(block >> 18u) & 0x3Fu]);
        out.push_back(kAlphabet[(block >> 12u) & 0x3Fu]);
        out.push_back(kAlphabet[(block >> 6u) & 0x3Fu]);
        out.push_back(kAlphabet[block & 0x3Fu]);
        index += 3u;
    }
    const std::size_t remaining = bytes.size() - index;
    if (remaining == 1u) {
        const std::uint32_t block = static_cast<std::uint32_t>(bytes[index]) << 16u;
        out.push_back(kAlphabet[(block >> 18u) & 0x3Fu]);
        out.push_back(kAlphabet[(block >> 12u) & 0x3Fu]);
        out.push_back('=');
        out.push_back('=');
    } else if (remaining == 2u) {
        const std::uint32_t block = (static_cast<std::uint32_t>(bytes[index]) << 16u) |
                                    (static_cast<std::uint32_t>(bytes[index + 1u]) << 8u);
        out.push_back(kAlphabet[(block >> 18u) & 0x3Fu]);
        out.push_back(kAlphabet[(block >> 12u) & 0x3Fu]);
        out.push_back(kAlphabet[(block >> 6u) & 0x3Fu]);
        out.push_back('=');
    }
    return out;
}

// Appends explicit little-endian bytes to a growing fixture buffer.
class ByteWriter {
public:
    void append(const std::vector<std::uint8_t>& bytes) {
        data_.insert(data_.end(), bytes.begin(), bytes.end());
    }

    void appendRaw(std::size_t count, std::uint8_t value) {
        data_.insert(data_.end(), count, value);
    }

    std::size_t size() const { return data_.size(); }

    const std::vector<std::uint8_t>& bytes() const { return data_; }

private:
    std::vector<std::uint8_t> data_;
};

inline void appendU32LE(std::vector<std::uint8_t>& out, std::uint32_t value) {
    out.push_back(static_cast<std::uint8_t>(value & 0xFFu));
    out.push_back(static_cast<std::uint8_t>((value >> 8u) & 0xFFu));
    out.push_back(static_cast<std::uint8_t>((value >> 16u) & 0xFFu));
    out.push_back(static_cast<std::uint8_t>((value >> 24u) & 0xFFu));
}

// Builds a binary glTF (GLB) container: a 12-byte header, a JSON chunk padded
// with spaces and a BIN chunk padded with zeroes. The caller supplies the
// document text and the binary chunk; this only frames known bytes.
inline std::vector<std::uint8_t> makeGlb(const std::string& json,
                                         const std::vector<std::uint8_t>& binary) {
    std::vector<std::uint8_t> jsonChunk(json.begin(), json.end());
    while (jsonChunk.size() % 4u != 0u) jsonChunk.push_back(' ');
    std::vector<std::uint8_t> binChunk = binary;
    while (binChunk.empty() || binChunk.size() % 4u != 0u) binChunk.push_back(0u);

    std::vector<std::uint8_t> out;
    out.reserve(12u + 8u + jsonChunk.size() + 8u + binChunk.size());
    appendU32LE(out, 0x46546C67u);  // "glTF"
    appendU32LE(out, 2u);
    appendU32LE(out, static_cast<std::uint32_t>(12u + 8u + jsonChunk.size() + 8u +
                                               binChunk.size()));
    appendU32LE(out, static_cast<std::uint32_t>(jsonChunk.size()));
    appendU32LE(out, 0x4E4F534Au);  // "JSON"
    out.insert(out.end(), jsonChunk.begin(), jsonChunk.end());
    appendU32LE(out, static_cast<std::uint32_t>(binChunk.size()));
    appendU32LE(out, 0x004E4942u);  // "BIN\0"
    out.insert(out.end(), binChunk.begin(), binChunk.end());
    return out;
}

// Compares dimensions and every RGBA byte against a literal expectation.
// The message names the context, the first differing byte and its pixel.
inline bool expectTexturePixels(const std::vector<std::uint8_t>& actual,
                                std::size_t actualWidth,
                                std::size_t actualHeight,
                                const ImageFixture& expected,
                                const std::string& context,
                                std::string& outFail) {
    if (actualWidth != expected.width || actualHeight != expected.height) {
        outFail = context + ": size " + std::to_string(actualWidth) + "x" +
                  std::to_string(actualHeight) + " != expected " +
                  std::to_string(expected.width) + "x" +
                  std::to_string(expected.height);
        return false;
    }
    if (actual.size() != expected.rgba.size()) {
        outFail = context + ": rgba byte count " + std::to_string(actual.size()) +
                  " != expected " + std::to_string(expected.rgba.size());
        return false;
    }
    static const char* kChannelName[4] = {"R", "G", "B", "A"};
    for (std::size_t i = 0; i < actual.size(); ++i) {
        if (actual[i] == expected.rgba[i]) continue;
        const std::size_t pixel = i / 4u;
        const std::size_t channel = i % 4u;
        const std::size_t x = pixel % expected.width;
        const std::size_t y = pixel / expected.width;
        outFail = context + ": pixel (" + std::to_string(x) + "," +
                  std::to_string(y) + ") channel " + kChannelName[channel] +
                  " actual " + std::to_string(actual[i]) + " " + hexByte(actual[i]) +
                  " != expected " + std::to_string(expected.rgba[i]) + " " +
                  hexByte(expected.rgba[i]);
        return false;
    }
    return true;
}

// Compares a decoded texture's sampler metadata (GL enums stored as ints).
inline bool expectTextureEnums(int actualWrapS,
                               int actualWrapT,
                               int actualMinF,
                               int actualMagF,
                               int expectedWrapS,
                               int expectedWrapT,
                               int expectedMinF,
                               int expectedMagF,
                               const std::string& context,
                               std::string& outFail) {
    const auto field = [&](const char* name, int actual, int expected) {
        if (actual == expected) return true;
        outFail = context + ": " + name + " " + std::to_string(actual) +
                  " != expected " + std::to_string(expected);
        return false;
    };
    if (!field("wrapS", actualWrapS, expectedWrapS)) return false;
    if (!field("wrapT", actualWrapT, expectedWrapT)) return false;
    if (!field("minF", actualMinF, expectedMinF)) return false;
    return field("magF", actualMagF, expectedMagF);
}

